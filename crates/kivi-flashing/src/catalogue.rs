pub const CATALOGUE_LEN: usize = VENDOR_CATALOGUE.len();

/// Searches the catalogue by case-insensitive substring.
pub fn search_catalogue(query: &str) -> Vec<&'static CatalogueEntry> {
    if query.trim().is_empty() {
        return Vec::new();
    }
    let needle = query.to_ascii_lowercase();
    VENDOR_CATALOGUE
        .iter()
        .filter(|e| e.description.to_ascii_lowercase().contains(&needle))
        .collect()
}

/// Entries that support a direct read.
pub fn direct_read_capable() -> Vec<&'static CatalogueEntry> {
    VENDOR_CATALOGUE.iter().filter(|e| e.direct_read).collect()
}
