//! Vehicle & ECU protocol capability catalogue (185 module groups, 726 vehicle/ECU variants).
//!
//! ## Scope
//!
//! This table acts as a **coverage reference** listing vehicle/ECU variants and
//! capability flags (`RD`/`VR`/`WR`/`CK`/`NC`). It does **not** publish MCU
//! family, flash size, or EEPROM size — those fields remain `None` unless
//! verified against the ECU itself before any flash is attempted.
//!
//! ## What this table does NOT carry
//!
//! The source document lists vehicle, engine and capability flags only. It does
//! **not** publish MCU family, flash size or EEPROM size. Those fields are
//! therefore `None` here rather than invented. A module with unknown technical
//! detail must be resolved against the ECU itself before any flash is attempted.
//!
//! ## Capability flags
//!
//! * `RD` — direct read
//! * `VR` — virtual read (Cal-ID + server file)
//! * `WR` — write
//! * `CK` — checksum / CVN correction
//! * `NC` — checksums not used

/// One vehicle variant from the reference catalogue.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CatalogueEntry {
    /// Vehicle / ECU description as published.
    pub description: &'static str,
    /// Direct read supported (`RD`).
    pub direct_read: bool,
    /// Virtual read supported (`VR`).
    pub virtual_read: bool,
    /// Write supported (`WR`).
    pub write_flash: bool,
    /// Checksum correction supported (`CK`).
    pub checksum_correct: bool,
    /// Checksums not used (`NC`).
    pub no_checksum: bool,
}

/// Builds one entry from a flag string like `"RDWRCK"`.
const fn entry(description: &'static str, flags: &'static str) -> CatalogueEntry {
    let b = flags.as_bytes();
    let mut i = 0;
    let (mut rd, mut vr, mut wr, mut ck, mut nc) = (false, false, false, false, false);
    while i + 1 < b.len() + 1 {
        if i + 2 > b.len() { break; }
        let a = b[i];
        let c = b[i + 1];
        if a == b'R' && c == b'D' { rd = true; i += 2; continue; }
        if a == b'V' && c == b'R' { vr = true; i += 2; continue; }
        if a == b'W' && c == b'R' { wr = true; i += 2; continue; }
        if a == b'C' && c == b'K' { ck = true; i += 2; continue; }
        if a == b'N' && c == b'C' { nc = true; i += 2; continue; }
        i += 1;
    }
    CatalogueEntry { description, direct_read: rd, virtual_read: vr,
                      write_flash: wr, checksum_correct: ck, no_checksum: nc }
}

