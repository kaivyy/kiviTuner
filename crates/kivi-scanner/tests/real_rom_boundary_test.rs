/// What the detector does at one fixture.
struct Probe {
    name: &'static str,
    oracle_offset: usize,
    rows: usize,
    cols: usize,
    /// Start offsets (in fixture coordinates) of every window overlapping the oracle.
    starts: Vec<usize>,
    /// Offset of the window with the highest confidence.
    best_confidence_start: Option<usize>,
    /// Offset of the window whose start is nearest the oracle.
    nearest_start: Option<usize>,
}

fn probe(fixture: &(&'static str, usize, usize, usize, usize, &'static [u8])) -> Probe {
    let (name, _base, oracle_off, rows, cols, bytes) = *fixture;
    let span = rows * cols * 2;
    let oracle_end = oracle_off + span;

    let mut starts: Vec<usize> = Vec::new();
    let mut best_conf: Option<(usize, f64)> = None;

    if rows >= 2 && cols >= 2 {
        let tables = scan_16bit_tables_auto_endian(bytes, &[(rows, cols)], 0, bytes.len());
        for t in &tables {
            let e = t.z_address + t.rows * t.cols * 2;
            if t.z_address < oracle_end && oracle_off < e {
                starts.push(t.z_address);
                if best_conf.is_none_or(|(_, c)| t.confidence_score > c) {
                    best_conf = Some((t.z_address, t.confidence_score));
                }
            }
        }
    } else {
        let n = rows.max(cols);
        let curves = scan_curves(
            bytes,
            &CurveScanOptions {
                min_points: 3,
                max_points: 40,
                endian: Endian::Big,
                include_8bit: false,
                allow_monotonic: true,
                snap_boundaries: true,
            },
        );
        for c in &curves {
            let e = c.address + c.points * c.cell_bytes;
            if c.address < oracle_end && oracle_off < e {
                starts.push(c.address);
                // Curve confidence is not exposed; treat the longest as best.
                if best_conf.is_none_or(|(_, v)| (c.points as f64) > v) {
                    best_conf = Some((c.address, c.points as f64));
                }
            }
        }
        let _ = n;
    }

    starts.sort_unstable();
    starts.dedup();
    let nearest = starts
        .iter()
        .copied()
        .min_by_key(|s| s.abs_diff(oracle_off));

    Probe {
        name,
        oracle_offset: oracle_off,
        rows,
        cols,
        starts: starts.clone(),
        best_confidence_start: best_conf.map(|(s, _)| s),
        nearest_start: nearest,
    }
}

fn all() -> Vec<Probe> {
    [CBR_TPS_AXIS, CBR_MAP_AXIS, CBR_RPM_AXIS, CBR_MAP_35X25, CBR_MAP_2]
        .iter()
        .map(probe)
        .collect()
}

#[test]
fn every_fixture_is_the_declared_size() {
    for f in [CBR_TPS_AXIS, CBR_MAP_AXIS, CBR_RPM_AXIS, CBR_MAP_35X25, CBR_MAP_2] {
        let (name, _, oracle_off, rows, cols, bytes) = f;
        let span = rows * cols * 2;
        assert!(
            oracle_off + span <= bytes.len(),
            "{name}: declared table runs past the fixture"
        );
        assert!(
            oracle_off >= 128 || bytes.len() > span,
            "{name}: fixture must contain real bytes before the table"
        );
    }
}

/// The oracle table's own cells must actually be readable and non-constant —
/// otherwise the fixture proves nothing.
#[test]
fn every_fixture_holds_a_real_table() {
    for f in [CBR_TPS_AXIS, CBR_MAP_AXIS, CBR_RPM_AXIS, CBR_MAP_35X25, CBR_MAP_2] {
        let (name, _, oracle_off, rows, cols, bytes) = f;
        let n = rows * cols;
        let mut vals = Vec::with_capacity(n);
        for i in 0..n {
            let o = oracle_off + i * 2;
            vals.push(u16::from_be_bytes([bytes[o], bytes[o + 1]]));
        }
        let uniq: std::collections::HashSet<u16> = vals.iter().copied().collect();
        assert!(uniq.len() > 1, "{name}: table cells are constant");
    }
}

