use kivi_scanner::boundary_snap::snap_monotonic;
use kivi_scanner::curve_scan::Endian as ScanEndian;

/// One 1-D fixture plus the byte order its cells use.
struct OneD {
    name: &'static str,
    oracle_off: usize,
    points: usize,
    bytes: &'static [u8],
    endian: ScanEndian,
    /// Extra cells that are known to precede the oracle but cannot be separated
    /// from it by any gradient rule. See the B58_1 comment.
    inseparable_head_cells: usize,
}

fn one_d_fixtures() -> Vec<OneD> {
    let mut v = Vec::new();
    for (name, _b, off, rows, cols, bytes) in [CBR_TPS_AXIS, CBR_MAP_AXIS, CBR_RPM_AXIS] {
        v.push(OneD {
            name,
            oracle_off: off,
            points: rows * cols,
            bytes,
            endian: ScanEndian::Big,
            inseparable_head_cells: 0,
        });
    }
    for (name, _b, off, rows, cols, bytes) in [B58_1, B58_2, B58_3] {
        v.push(OneD {
            name,
            oracle_off: off,
            points: rows * cols,
            bytes,
            endian: ScanEndian::Little,
            // B58_1's window opens `4000, 3800, 1542, 1700, ...`. The `1542` is
            // a valid-looking first cell (`[1542, 1700, 2000, ...]` is strictly
            // ascending with step 158, inside the body's own 300-1000 range), so
            // no gradient rule may remove it without also removing genuine
            // low-valued first cells. It is therefore reported, not hidden.
            inseparable_head_cells: if name == "B58_1_0x700F82" { 1 } else { 0 },
        });
    }
    v
}

fn decode_cells(f: &OneD, at: usize, n: usize) -> Vec<u16> {
    (0..n)
        .map(|i| {
            let o = at + i * 2;
            match f.endian {
                ScanEndian::Big => u16::from_be_bytes([f.bytes[o], f.bytes[o + 1]]),
                ScanEndian::Little => u16::from_le_bytes([f.bytes[o], f.bytes[o + 1]]),
            }
        })
        .collect()
}

/// Snapping must never move a window that already starts at the oracle, and
/// must not invent a start for a window that begins inside the table.
///
/// This runs on every covering window of every fixture, not just the longest
/// one, because a 1-D axis is typically covered by several partial windows and
/// no single one of them is privileged.
#[test]
fn snapping_never_makes_a_window_worse() {
    let mut worse = Vec::new();
    for f in one_d_fixtures() {
        let oracle_end = f.oracle_off + f.points * 2;
        let curves = scan_curves(
            f.bytes,
            &CurveScanOptions {
                min_points: 3,
                max_points: 64,
                endian: f.endian,
                include_8bit: false,
                allow_monotonic: true,
                snap_boundaries: true,
            },
        );
        for c in curves.iter() {
            let e = c.address + c.points * c.cell_bytes;
            if !(c.address < oracle_end && e > f.oracle_off) {
                continue;
            }
            let before = (c.address as i64 - f.oracle_off as i64).abs();
            let vals = decode_cells(&f, c.address, c.points);
            let Some(s) = snap_monotonic(&vals) else { continue };
            let after = ((c.address + s.trimmed_head * 2) as i64 - f.oracle_off as i64).abs();
            if after > before {
                worse.push((f.name, c.address, before, after));
            }
        }
    }
    assert!(
        worse.is_empty(),
        "snapping moved a window further from the oracle: {worse:?}"
    );
}

/// Reports, per fixture, the best snapped start any covering window reaches.
///
/// The honest headline number is the count of fixtures where some window snaps
/// exactly onto the oracle. It is asserted as a floor, not as a target, so a
/// regression is caught while further gains stay possible.
#[test]
fn snapping_recovers_exact_starts_on_real_fixtures() {
    let mut exact = 0usize;
    let mut considered = 0usize;

    for f in one_d_fixtures() {
        let oracle_end = f.oracle_off + f.points * 2;
        let curves = scan_curves(
            f.bytes,
            &CurveScanOptions {
                min_points: 3,
                max_points: 64,
                endian: f.endian,
                include_8bit: false,
                allow_monotonic: true,
                snap_boundaries: true,
            },
        );

        let covering: Vec<_> = curves
            .iter()
            .filter(|c| {
                let e = c.address + c.points * c.cell_bytes;
                e > f.oracle_off && c.address < oracle_end
            })
            .collect();
        if covering.is_empty() {
            eprintln!("{}: no covering curve", f.name);
            continue;
        }
        considered += 1;

        let mut best: Option<i64> = None;
        for c in &covering {
            let vals = decode_cells(&f, c.address, c.points);
            let Some(s) = snap_monotonic(&vals) else { continue };
            let delta = (c.address + s.trimmed_head * 2) as i64 - f.oracle_off as i64;
            if best.is_none_or(|b| delta.abs() < b.abs()) {
                best = Some(delta);
            }
        }
        let best = best.unwrap_or(i64::MIN);
        let hit = best.abs() <= f.inseparable_head_cells as i64 * 2;
        if best == 0 {
            exact += 1;
        }
        eprintln!(
            "{}: windows={} best snapped delta={:+}{}",
            f.name,
            covering.len(),
            best,
            if best == 0 {
                "  EXACT"
            } else if hit {
                "  within the inseparable cell"
            } else {
                ""
            }
        );
    }

    eprintln!("SNAPPED EXACT {exact}/{considered}");
    assert!(considered >= 6, "expected six 1-D fixtures, saw {considered}");
    assert!(
        exact >= 2,
        "snapping recovered only {exact}/{considered} exact starts; \
         B58_2 and B58_3 were exact before and must stay exact"
    );
}

