//! LAPIS 1.5 — REAL-BYTE FIXTURES for boundary localisation.
//!
//! ## Why this file exists
//!
//! Earlier unit tests planted curves in a run of `0x00` padding. That makes the
//! test sterile: in a real ROM the bytes on both sides of a table are live data,
//! so a monotonic run continues into its neighbours and the detector starts
//! early (`pre-bleeding`). Measured on the CBR250RR ROM, a declared 25-point
//! axis at `0x04FF80` is found as a 22-point run starting at `0x04FF78` — 8
//! bytes early — because `33, 1500, 33, 0` reads as part of the run.
//!
//! These fixtures are **verbatim ROM bytes** (±128 around each table), so a test
//! here fails for the same reason the scanner fails on the real binary.
//!
//! ## What is measured
//!
//! Not recall. The question is only: at what offset does the current detector
//! start its window, relative to the oracle address? That number is the target
//! for boundary snapping.
//!
//! ## Provenance
//!
//! `CBR250RR-38770-K64-ND1_BIN.bin`, 1 048 576 bytes. Extracted read-only; the
//! source file is never modified.

